import mongoose from 'mongoose';

const { ObjectId } = mongoose.Schema.Types;

const attachmentSchema = new mongoose.Schema(
  {
    url: { type: String, required: true },
    publicId: { type: String, required: true },
    resourceType: { type: String, enum: ['image', 'raw'], required: true },
    name: { type: String, maxlength: 200 },
    size: { type: Number },
    mimeType: { type: String },
    width: { type: Number },
    height: { type: Number },
  },
  { _id: false },
);

const messageSchema = new mongoose.Schema(
  {
    senderId: { type: ObjectId, ref: 'User', required: true },
    receiverId: { type: ObjectId, ref: 'User', required: true },
    conversationKey: { type: String, required: true },
    type: { type: String, enum: ['text', 'image', 'file'], default: 'text' },
    text: { type: String, trim: true, maxlength: 2000, default: '' },
    attachment: { type: attachmentSchema, default: undefined },
    status: { type: String, enum: ['sent', 'delivered', 'read'], default: 'sent' },
    deliveredAt: { type: Date, default: null },
    readAt: { type: Date, default: null },
    // Generated by the sender's browser; makes retries idempotent.
    clientMessageId: { type: String, required: true, maxlength: 64 },
  },
  {
    timestamps: true,
    toJSON: {
      versionKey: false,
      transform(_doc, ret) {
        return toPublicMessage(ret);
      },
    },
  },
);

// Chat history + cursor pagination: one range scan per page.
messageSchema.index({ conversationKey: 1, createdAt: -1, _id: -1 });
// Pending deliveries and unread counts for a receiver.
messageSchema.index({ receiverId: 1, status: 1 });
// Contacts list: latest message per conversation for a sender.
messageSchema.index({ senderId: 1, createdAt: -1 });
// A retried send with the same clientMessageId can never create a duplicate.
messageSchema.index({ senderId: 1, clientMessageId: 1 }, { unique: true });

export const Message = mongoose.models.Message ?? mongoose.model('Message', messageSchema);

/** Strip internal fields. Works for documents' toJSON output and lean objects. */
export function toPublicMessage(m) {
  if (!m) return m;
  const { __v, conversationKey, ...rest } = m;
  const out = {
    ...rest,
    _id: String(m._id),
    senderId: String(m.senderId),
    receiverId: String(m.receiverId),
  };
  if (m.attachment) {
    const { publicId, ...attachment } = m.attachment;
    out.attachment = attachment;
  }
  return out;
}
